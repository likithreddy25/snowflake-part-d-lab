USE ROLE PARTD_ENGINEER;
USE WAREHOUSE WH_PARTD;
USE DATABASE PARTD_LAB;
USE SCHEMA RAW;

CREATE TABLE IF NOT EXISTS RAW.PRESCRIBER_CLAIMS (
    PRSCRBR_NPI NUMBER NOT NULL,
    PRSCRBR_LAST_ORG_NAME VARCHAR,
    PRSCRBR_FIRST_NAME VARCHAR,
    PRSCRBR_CITY VARCHAR,
    PRSCRBR_STATE_ABRVTN VARCHAR(2) NOT NULL,
    PRSCRBR_TYPE VARCHAR,
    BRND_NAME VARCHAR NOT NULL,
    GNRC_NAME VARCHAR,
    TOT_CLMS NUMBER NOT NULL,
    TOT_30DAY_FILLS NUMBER,
    TOT_DAY_SUPLY NUMBER,
    TOT_DRUG_CST DECIMAL(15, 2) NOT NULL,
    TOT_BENES NUMBER,
    LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    LOADED_BY VARCHAR DEFAULT CURRENT_USER()
) COMMENT = 'Raw Medicare Part D prescriber claims, CMS 2024 (first 25 states alphabetically, up to 20,000 rows each in NPI order)';

CREATE STREAM IF NOT EXISTS RAW.STREAM_PRESCRIBER_CLAIMS
    ON TABLE RAW.PRESCRIBER_CLAIMS APPEND_ONLY = FALSE;

COPY INTO RAW.PRESCRIBER_CLAIMS (
    PRSCRBR_NPI, PRSCRBR_LAST_ORG_NAME, PRSCRBR_FIRST_NAME, PRSCRBR_CITY,
    PRSCRBR_STATE_ABRVTN, PRSCRBR_TYPE, BRND_NAME, GNRC_NAME, TOT_CLMS,
    TOT_30DAY_FILLS, TOT_DAY_SUPLY, TOT_DRUG_CST, TOT_BENES)
FROM (
    SELECT $1::NUMBER, $2::VARCHAR, $3::VARCHAR, $4::VARCHAR, $5::VARCHAR,
           $6::VARCHAR, $7::VARCHAR, $8::VARCHAR, $9::NUMBER, $10::NUMBER,
           $11::NUMBER, $12::DECIMAL(15,2), $13::NUMBER
    FROM @PARTD_LAB.RAW.STG_PARTD/cms_partd_20261009_115856.csv
)
FILE_FORMAT = (TYPE = 'CSV' SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"'
               NULL_IF = ('') EMPTY_FIELD_AS_NULL = TRUE)
ON_ERROR = 'ABORT_STATEMENT'
PURGE = FALSE;

-- Reconcile against the downloader metadata (500,000 rows; 20,252 prescribers; 25 states; $3,996,523,549.72)
SELECT COUNT(*) AS row_count,
       COUNT(DISTINCT PRSCRBR_NPI) AS unique_prescribers,
       COUNT(DISTINCT PRSCRBR_STATE_ABRVTN) AS unique_states,
       COUNT(DISTINCT BRND_NAME) AS unique_brand_names,
       SUM(TOT_DRUG_CST) AS total_cost,
       COUNT_IF(TOT_BENES IS NULL) AS null_tot_benes
FROM RAW.PRESCRIBER_CLAIMS;

USE SCHEMA STAGING;
CREATE TABLE IF NOT EXISTS STAGING.PRESCRIBER_CLAIMS_DEDUPED LIKE RAW.PRESCRIBER_CLAIMS;

CREATE OR REPLACE TASK TASK_INCREMENTAL_MERGE
    WAREHOUSE = WH_PARTD
    SCHEDULE = '60 MINUTE'
    WHEN SYSTEM$STREAM_HAS_DATA('RAW.STREAM_PRESCRIBER_CLAIMS')
AS
MERGE INTO STAGING.PRESCRIBER_CLAIMS_DEDUPED tgt
USING (SELECT * FROM RAW.STREAM_PRESCRIBER_CLAIMS WHERE METADATA$ACTION = 'INSERT') src
ON tgt.PRSCRBR_NPI = src.PRSCRBR_NPI
   AND tgt.PRSCRBR_STATE_ABRVTN = src.PRSCRBR_STATE_ABRVTN
   AND tgt.BRND_NAME = src.BRND_NAME
   AND tgt.GNRC_NAME = src.GNRC_NAME
WHEN MATCHED THEN UPDATE SET
    TOT_CLMS = src.TOT_CLMS, TOT_30DAY_FILLS = src.TOT_30DAY_FILLS,
    TOT_DAY_SUPLY = src.TOT_DAY_SUPLY, TOT_DRUG_CST = src.TOT_DRUG_CST,
    TOT_BENES = src.TOT_BENES, LOADED_AT = src.LOADED_AT
WHEN NOT MATCHED THEN INSERT (PRSCRBR_NPI, PRSCRBR_LAST_ORG_NAME, PRSCRBR_FIRST_NAME, PRSCRBR_CITY,
    PRSCRBR_STATE_ABRVTN, PRSCRBR_TYPE, BRND_NAME, GNRC_NAME, TOT_CLMS, TOT_30DAY_FILLS,
    TOT_DAY_SUPLY, TOT_DRUG_CST, TOT_BENES, LOADED_AT, LOADED_BY)
VALUES (src.PRSCRBR_NPI, src.PRSCRBR_LAST_ORG_NAME, src.PRSCRBR_FIRST_NAME, src.PRSCRBR_CITY,
    src.PRSCRBR_STATE_ABRVTN, src.PRSCRBR_TYPE, src.BRND_NAME, src.GNRC_NAME, src.TOT_CLMS,
    src.TOT_30DAY_FILLS, src.TOT_DAY_SUPLY, src.TOT_DRUG_CST, src.TOT_BENES, src.LOADED_AT, src.LOADED_BY);

ALTER TASK TASK_INCREMENTAL_MERGE SUSPEND;
SHOW TASKS LIKE 'TASK_INCREMENTAL_MERGE' IN SCHEMA PARTD_LAB.STAGING;